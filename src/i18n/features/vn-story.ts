type VnStoryLang = keyof typeof COPY;

export type VnStoryMsgKey = keyof (typeof COPY)["zh-TW"];
export const VN_STORY_MESSAGE_KEYS = Object.keys(COPY["zh-TW"]) as VnStoryMsgKey[];

export function isVnStoryMsgKey(key: string): key is VnStoryMsgKey {
  return typeof key === "string" && key in COPY["zh-TW"];
}

export function vnStoryMessage(lang: VnStoryLang, key: VnStoryMsgKey): string {
  return COPY[lang][key];
}
