type RoomLang = keyof typeof COPY;

export type RoomMsgKey = keyof (typeof COPY)["zh-TW"];
export const ROOM_MESSAGE_KEYS = Object.keys(COPY["zh-TW"]) as RoomMsgKey[];

export function isRoomMsgKey(key: string): key is RoomMsgKey {
  // 與其他補充字典一樣容忍非字串鍵（既有呼叫端可能傳 undefined 進 t()）
  return typeof key === "string" && key in COPY["zh-TW"];
}

export function roomMessage(lang: RoomLang, key: RoomMsgKey): string {
  return COPY[lang][key];
}
