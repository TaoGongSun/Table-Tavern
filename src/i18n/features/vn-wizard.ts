type VnWizardLang = keyof typeof COPY;

export type VnWizardMsgKey = keyof (typeof COPY)["zh-TW"];
export const VN_WIZARD_MESSAGE_KEYS = Object.keys(COPY["zh-TW"]) as VnWizardMsgKey[];

export function isVnWizardMsgKey(key: string): key is VnWizardMsgKey {
  return typeof key === "string" && key in COPY["zh-TW"];
}

export function vnWizardMessage(lang: VnWizardLang, key: VnWizardMsgKey): string {
  return COPY[lang][key];
}
